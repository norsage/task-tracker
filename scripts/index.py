#!/usr/bin/env python3
"""Render the board's `_index.md` — a generated view, never hand-edited.

A tracker is a status field on the unit of work plus an index derived from it.
The status in each task's frontmatter is authoritative; this file is a view.
That ordering is the whole point: a hand-maintained index is a second list
living apart from the thing it tracks, so it becomes the stale copy and loses.

`next.py --all` answers a different question — what may I claim right now —
and deliberately shows only *eligible* tasks. The index shows everything,
grouped by status, so "what is in flight?" has an answer that does not depend
on eligibility.

Usage:
    index.py [--board BOARD] [--root ROOT] [--check]

`--check` writes nothing and exits non-zero if the file on disk differs from
what would be generated, which is the form an invariant check wants.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _common import (  # noqa: E402
    board_dir, display_id, find_duplicate_ids, find_root, id_sort_key,
    iter_task_files, load_config, parse_frontmatter, parse_id,
)

HEADER = """<!-- GENERATED by task-tracker index.py — do not edit by hand.
     The `status:` field in each task file is authoritative; this is a view.
     Regenerate: index.py --board '' -->

# Task board
"""

# Display order, and the heading each status appears under.
GROUPS = [
    ("in-progress", "In progress"),
    ("blocked", "Blocked"),
    ("planned", "Planned"),
    ("idea", "Ideas"),
    ("done", "Done"),
    ("abandoned", "Abandoned"),
]


def _rel(path: Path, folder: Path) -> str:
    """Link target relative to the index, which sits in `folder`."""
    rel = path.relative_to(folder).as_posix()
    # A directory-shaped task is NNNN-slug/README.md; link to the directory.
    return rel[: -len("/README.md")] + "/" if rel.endswith("/README.md") else rel


def render(root: Path, board: str | None = None) -> str:
    folder = board_dir(root, "tasks", board)
    width = load_config(root, board)["id_width"]
    rows: dict[str, list[tuple[str, str, str, str]]] = {}
    for p in iter_task_files(folder):
        try:
            meta, _ = parse_frontmatter(p.read_text())
        except Exception as exc:
            print(f"warning: skipping {p}: {exc}", file=sys.stderr)
            continue
        if parse_id(meta.get("id"))[0] is None:
            continue
        rows.setdefault(str(meta.get("status", "")), []).append(
            (
                display_id(meta["id"], width),
                str(meta.get("title", "")),
                str(meta.get("description", "")),
                _rel(p, folder),
            )
        )

    out = [HEADER]
    known = {s for s, _ in GROUPS}
    for status, heading in GROUPS:
        group = sorted(rows.get(status, []), key=lambda r: id_sort_key(r[0]))
        if not group:
            continue
        out.append(f"\n## {heading}\n")
        for tid, title, desc, link in group:
            line = f"- **[{tid}]({link})** {title}"
            if desc:
                line += f" — {desc}"
            out.append(line)

    unknown = sorted(set(rows) - known)
    if unknown:
        out.append("\n## Unrecognised status\n")
        for status in unknown:
            for tid, title, _, link in sorted(rows[status], key=lambda r: id_sort_key(r[0])):
                out.append(f"- **[{tid}]({link})** {title} — `status: {status}`")

    total = sum(len(v) for v in rows.values())
    out.append(f"\n---\n\n{total} task(s). Chores live in `_backlog.md`.\n")
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--root")
    ap.add_argument("--board")
    ap.add_argument(
        "--check",
        action="store_true",
        help="write nothing; exit 1 if _index.md is stale",
    )
    args = ap.parse_args()

    root = Path(args.root).resolve() if args.root else find_root()
    folder = board_dir(root, "tasks", args.board)
    if not folder.is_dir():
        print(f"no task board at {folder}", file=sys.stderr)
        return 2

    # Both counters, because `spec: 0012` is a reference too and goes
    # ambiguous the same way a task reference does.
    dupes = {}
    for kind in ("tasks", "specs"):
        dupes.update(find_duplicate_ids(root, kind, args.board))
    if dupes:
        print("duplicate ids — two writers minted the same one:", file=sys.stderr)
        for dup, paths in sorted(dupes.items()):
            print(f"  {dup}", file=sys.stderr)
            for p in paths:
                print(f"    {p}", file=sys.stderr)
        print("fix: give one of each pair a fresh suffix, then update references "
              "to it", file=sys.stderr)

    try:
        text = render(root, args.board)
    except ValueError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    target = folder / "_index.md"

    if args.check:
        if dupes:
            return 1
        current = target.read_text() if target.exists() else ""
        if current != text:
            print(f"{target} is stale — regenerate with index.py", file=sys.stderr)
            return 1
        print(f"{target} up to date")
        return 0

    target.write_text(text)
    print(f"wrote {target}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
